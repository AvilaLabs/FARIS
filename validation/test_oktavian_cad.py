def icosphere(radius: float, level: int):
    """Vertices and triangles of a subdivided icosahedron with every vertex on the sphere."""
    t = (1 + 5 ** 0.5) / 2
    v = [(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t), (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)]
    f = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8), (3, 9, 4), (3, 4, 2), (3, 2, 6),
         (3, 6, 8), (3, 8, 9), (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1)]

    def unit(p):
        n = math.sqrt(sum(x * x for x in p))
        return tuple(radius * x / n for x in p)

    verts = [unit(p) for p in v]
    cache = {}

    def midpoint(a, b):
        key = tuple(sorted((a, b)))
        if key not in cache:
            verts.append(unit(tuple((verts[a][i] + verts[b][i]) / 2 for i in range(3))))
            cache[key] = len(verts) - 1
        return cache[key]

    for _ in range(level):
        nf = []
        for a, b, c in f:
            ab, bc, ca = midpoint(a, b), midpoint(b, c), midpoint(c, a)
            nf += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
        f = nf
    return [list(p) for p in verts], [list(t_) for t_ in f]


class CadCaseManifest(unittest.TestCase):
    def setUp(self):
        self.m = M.load_manifest(CASES / "oktavian-al-cad" / "manifest.json")

    def test_shape_and_class(self):
        m = self.m
        self.assertEqual((m["evidence_class"], m["geometry_path"], m["source"]["commit"]), ("experiment", "CAD", OFB_COMMIT))
        self.assertEqual(sum(1 for d in m["detectors"] if d["response_class"] == "neutron_leakage_spectrum"), 134)
        self.assertEqual(sum(1 for d in m["detectors"] if d["response_class"] == "photon_leakage_spectrum"), 57)
        self.assertTrue(all("blocked" in d for d in m["detectors"] if d["response_class"] == "photon_leakage_spectrum"))
        self.assertEqual([d["id"] for d in m["detectors"] if "blocked" in d and d["response_class"] == "neutron_leakage_spectrum"], ["n-0.10109"])

    # Rule-before-result; a Verifies marker for VAL-005 is left to the requirement owner (TRACE.md is regenerated by them).
    def test_the_rule_is_declared_with_its_date_and_before_any_record(self):
        m = self.m
        self.assertEqual(m["protocol"]["declared"], m["compatibility"]["declared"])
        self.assertEqual(m["compatibility"]["k"], 2.0)
        self.assertEqual(m["protocol"]["case_outcome"]["rule"][:13], "Counted over ")
        self.assertIn("geometry_path_comparison", m["protocol"])
        self.assertIsInstance(m["protocol"]["run_conditions"]["histories"], int)

    def test_the_step_file_is_pinned_by_its_lfs_object_id(self):
        pointer = next(f for f in self.m["files"] if f.get("lfs_object_sha256"))
        self.assertTrue(pointer["path_in_source"].endswith("lfs/benchmarks/oktavian/oktavian_a.step"))
        self.assertEqual(len(pointer["lfs_object_sha256"]), 64)
        self.assertEqual(len(pointer["lfs_submodule_commit"]), 40)

    def test_the_packaged_experiment_is_the_same_measurement(self):
        eq = self.m["equivalence"]
        self.assertAlmostEqual(eq["neutron"]["value_over_stored_min"], 4 * math.pi * 19.5 ** 2, delta=1e-6)
        self.assertAlmostEqual(eq["photon"]["error_over_stored_max"], 4 * math.pi * 19.5 ** 2, delta=1e-6)

    def test_source_histogram_is_probabilities_over_intervals(self):
        src = self.m["model"]["source"]
        self.assertEqual(len(src["energy_edges_ev"]), len(src["bin_probability"]) + 1)
        self.assertAlmostEqual(sum(src["bin_probability"]), 1.0027211682, places=9)
        x, p = RC.source_histogram(src["energy_edges_ev"], src["bin_probability"])
        # OpenMC's Tabular histogram weights a density by the interval width: the density must give back the probability.
        again = [p[i] * (x[i + 1] - x[i]) for i in range(len(p) - 1)]
        for a, b in zip(again, src["bin_probability"]):
            self.assertAlmostEqual(a, b, places=12)

    def test_materials_are_the_real_compositions_not_pure_cr50(self):
        steel = next(m for m in self.m["model"]["materials"] if m["name"] == "SS-304")
        self.assertGreater(len(steel["nuclides"]), 10)
        self.assertLess(steel["nuclides"]["Cr50"], 0.01)

    def test_defects_and_deviations_are_stated(self):
        self.assertGreaterEqual(len(self.m["known_upstream_defects"]), 3)
        self.assertTrue(self.m["protocol"]["deviations_from_the_ofb_specification"])

    @unittest.skipUnless((SOURCES / "openmc_fusion_benchmarks" / ".git").exists() and (SOURCES / "open-benchmarks" / ".git").exists(), "pinned checkouts not present")
    def test_hashes_match_when_the_pinned_checkouts_are_present(self):
        import subprocess
        head = subprocess.run(["git", "-C", str(SOURCES / "openmc_fusion_benchmarks"), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
