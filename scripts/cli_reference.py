"""The command-line reference, generated from `faris --help` (requirement DOC-021).

    python3 scripts/cli_reference.py --faris target/debug/faris           # write docs/guide/cli-reference.md
    python3 scripts/cli_reference.py --faris target/debug/faris --check   # fail if the page is out of date

Walks the binary's own help: the top level, then every subcommand listed under "Commands:", to any depth. Each
command gets its full help text, which names every flag, and an example: the first command line in the handbook
(README.md, docs/guide/*.md other than the reference itself) that starts with that command's words. A command
with no such example is listed as such at the top of the page, so the gap is visible instead of hidden. The page
is a function of the binary and the handbook, with no date, so `--check` is stable.

CI builds the debug binary for the documentation samples, then runs --check, so a command, flag or help text
that changes without the page changing fails. Help text that mentions a path or a default taken from the machine
would make the page differ between machines; the check would then fail in CI, which is the signal to fix the help.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = Path("docs") / "guide" / "cli-reference.md"
EXAMPLE_SOURCES = ["README.md", "docs/guide/*.md"]
TIMEOUT_S = 60


def run_help(binary: Path, words: tuple[str, ...]) -> str:
    out = subprocess.run([str(binary), *words, "--help"], capture_output=True, text=True, timeout=TIMEOUT_S)
    if out.returncode != 0:
        raise RuntimeError(f"`faris {' '.join(words)} --help` exited {out.returncode}: {out.stderr.strip()[:200]}")
    return out.stdout.rstrip("\n")


def subcommands(help_text: str) -> list[str]:
    names, inside = [], False
    for line in help_text.splitlines():
        if line.rstrip() == "Commands:":
            inside = True
        elif inside:
            if not line.strip():
                break
            match = re.match(r"^  ([a-z][a-z0-9-]*)(\s|$)", line)
            if match and match.group(1) != "help":
                names.append(match.group(1))
    return names


def walk(binary: Path, words: tuple[str, ...] = ()) -> list[tuple[tuple[str, ...], str]]:
    text = run_help(binary, words)
    found = [(words, text)]
    for name in subcommands(text):
        found += walk(binary, (*words, name))
    return found


def command_lines(root: Path) -> list[str]:
    """Command lines that start with `faris` in the handbook, continuation lines joined, in file order."""
    lines: list[str] = []
    files: list[Path] = []
    for pattern in EXAMPLE_SOURCES:
        files += sorted(root.glob(pattern))
    for path in files:
        if path.relative_to(root).as_posix() == PAGE.as_posix():
            continue
        in_fence, pending = False, ""
        for raw in path.read_text(encoding="utf-8").splitlines():
            if raw.strip().startswith("```"):
                in_fence, pending = not in_fence, ""
                continue
            if in_fence:
                piece = raw.strip()
                if pending:
                    piece = pending + " " + piece
                if piece.endswith("\\"):
                    pending = piece[:-1].strip()
                    continue
                pending = ""
                if piece.startswith("faris "):
                    lines.append(piece)
            else:
                lines += [m.strip() for m in re.findall(r"`(faris [^`]+)`", raw)]
    return lines


def example_for(words: tuple[str, ...], lines: list[str]) -> str | None:
    prefix = "faris " + " ".join(words) if words else "faris"
    for line in lines:
        if line == prefix or line.startswith(prefix + " "):
            return line
    return None


def render(commands: list[tuple[tuple[str, ...], str]], lines: list[str]) -> str:
    leaves = [(w, t) for w, t in commands if w]
    examples = {w: example_for(w, lines) for w, _ in leaves}
    missing = [w for w, e in examples.items() if e is None]
    out = [
        "<!-- kind: reference -->",
        "# Command-line reference",
        "",
        "<!-- Generated by scripts/cli_reference.py from `faris --help`. Do not edit by hand. -->",
        "",
        "Every `faris` command with its help text, which lists every option. The examples are command lines from the",
        "rest of this handbook; [Command line](cli.md) explains how the commands fit together.",
        "",
        f"{len(leaves) - len(missing)} of {len(leaves)} commands have an example in the handbook"
        + (f"; these have none yet: {', '.join('`faris ' + ' '.join(w) + '`' for w in missing)}." if missing else "."),
        "",
        "## faris",
        "",
        "```text",
        commands[0][1],
        "```",
        "",
    ]
    for words, text in leaves:
        out += [f"## faris {' '.join(words)}", "", "```text", text, "```", ""]
        example = examples[words]
        out += [f"Example: `{example}`", ""] if example else ["Example: none in the handbook yet.", ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--faris", required=True, type=Path, help="the faris binary")
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--check", action="store_true", help="fail if the page is not what a fresh generation gives")
    args = ap.parse_args(argv)
    try:
        text = render(walk(args.faris), command_lines(args.root))
    except (OSError, RuntimeError, subprocess.SubprocessError) as e:
        print(f"cli reference: {e}", file=sys.stderr)
        return 1
    page = args.root / PAGE
    if args.check:
        if not page.is_file() or page.read_text(encoding="utf-8") != text:
            print(f"{PAGE} is out of date; run python3 scripts/cli_reference.py --faris <binary>", file=sys.stderr)
            return 1
        print(f"cli reference: PASS, {PAGE} is current")
        return 0
    page.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
