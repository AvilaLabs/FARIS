"""Generate and check the requirements scorecard.

Reads the requirement tables in docs/requirements/ and the Verifies: markers
through scripts/requirement_trace.py, and writes docs/requirements/SCORECARD.md.
The scorecard is generated, never edited by hand. With --check it rewrites
nothing and fails when the committed file is stale.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import requirement_trace as rt

SCORECARD = rt.REQUIREMENTS / "SCORECARD.md"
PHASES = tuple(f"F{n}" for n in range(1, 8))
BASES = (("[V]", "[V]"), ("[U]", "[U]"), ("FARIS choice", "FARIS choice"), ("[internal]", "[internal]"))
LINK = re.compile(r"\[([^\]]+)\]\(https?://[^)]*\)")
# Outside tools and standards, matched as whole words in Basis and Target text.
KNOWN_TOOLS = ("OpenMC", "MCNP", "Serpent", "TRIPOLI", "FISPACT", "GMAT", "Blender", "Zed",
               "WCAG", "SCALE", "Geant4", "FLUKA", "PHITS", "ACTINV", "DAGMC", "ARIES", "ITER")
GENERIC_TEXTS = {"source", "report", "guide", "docs", "criteria"}


def link_name(text: str) -> str:
    """Clean a link text; empty when it is only a mark or a generic word."""
    text = text.strip()
    stripped = re.match(r"^[VU]: \[(.*)$", text)
    if stripped:
        text = stripped.group(1).strip()
    elif re.match(r"^[VU](,|$)", text):
        return ""
    return "" if text.lower() in GENERIC_TEXTS else text


def annotate(requirements: dict[str, dict], trace: dict[str, list[str]]) -> None:
    """Add the derived fields used by the scorecard to each requirement."""
    for rid, info in requirements.items():
        info["traced"] = rid in trace
        info["provisional"] = "(provisional:" in info.get("target", "")
        basis = info.get("basis", "")
        info["bases"] = [name for name, mark in BASES if mark in basis]


def tally(ids: list[str], requirements: dict[str, dict]) -> list[int]:
    """Counts in column order: total, statuses, traced, bases, no basis, provisional."""
    rows = [requirements[i] for i in ids]
    out = [len(rows)]
    out += [sum(1 for r in rows if r["now"] == s) for s in rt.STATUSES]
    out.append(sum(1 for r in rows if r["traced"]))
    out += [sum(1 for r in rows if name in r["bases"]) for name, _ in BASES]
    out.append(sum(1 for r in rows if not r["bases"]))
    out.append(sum(1 for r in rows if r["provisional"]))
    return out


def pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f} %" if whole else "n/a"


HEAD = ("Requirements", "Met", "Partial", "No", "Unmeasured", "Traced", "Traced %",
        "[V]", "[U]", "FARIS choice", "[internal]", "No basis", "Provisional")


def cells(counts: list[int]) -> list[str]:
    total, met, partial, unmeasured, no, traced, *rest = counts
    # Column order is Met, Partial, No, Unmeasured; rt.STATUSES is Met, Partial, Unmeasured, No.
    return [str(total), str(met), str(partial), str(no), str(unmeasured), str(traced), pct(traced, total)] + [
        str(n) for n in rest]


def table(label: str, rows: list[tuple[str, list[int]]]) -> list[str]:
    lines = [f"| {label} | " + " | ".join(HEAD) + " |", "| --- | " + " | ".join(["---:"] * len(HEAD)) + " |"]
    for name, counts in rows:
        lines.append(f"| {name} | " + " | ".join(cells(counts)) + " |")
    return lines


def peers(file_ids: list[str], requirements: dict[str, dict]) -> list[str]:
    links: dict[str, None] = {}
    tools: dict[str, None] = {}
    for rid in file_ids:
        text = requirements[rid]["basis"] + " " + requirements[rid]["target"]
        for match in LINK.finditer(text):
            name = link_name(match.group(1))
            if name:
                links[name] = None
        plain = LINK.sub(" ", text)
        for tool in KNOWN_TOOLS:
            if re.search(rf"\b{re.escape(tool)}\b", plain):
                tools[tool] = None
    return list(dict.fromkeys(list(tools) + list(links)))


def render(requirements: dict[str, dict], trace: dict[str, list[str]], titles: dict[str, str] | None = None) -> str:
    annotate(requirements, trace)
    titles = titles or {}
    by_file: dict[str, list[str]] = {}
    for rid, info in requirements.items():
        by_file.setdefault(info["file"], []).append(rid)
    all_ids = list(requirements)
    lines = [
        "# Requirements scorecard",
        "",
        "Generated by `scripts/requirement_scorecard.py`; do not edit by hand.",
        "",
        "Counts come from the requirement tables in this directory. The Now column is recorded by hand "
        "(see the [index](README.md) for its date) and a requirement counts as Met only when its own Now "
        "column says so. Traced means at least one test declares `Verifies:` for the requirement "
        "([TRACE.md](TRACE.md)); it says a test exists, not that the target is met, and CI decides whether "
        "that test passes. Basis columns count requirements that carry the mark; a requirement can carry "
        "more than one, so they need not add up to the total. Struck-through (withdrawn) requirements are "
        "excluded.",
        "",
        "## Overall",
        "",
    ]
    lines += table("Scope", [("All requirements", tally(all_ids, requirements))])
    lines += ["", "## By category", ""]
    rows = []
    for name in sorted(by_file):
        title = titles.get(name, name)
        rows.append((f"[{title}]({name})", tally(by_file[name], requirements)))
    lines += table("Category", rows)
    lines += ["", "## By phase", ""]
    phase_rows = []
    for phase in list(PHASES) + sorted({i["phase"] for i in requirements.values()} - set(PHASES)):
        ids = [r for r in all_ids if requirements[r]["phase"] == phase]
        if ids:
            phase_rows.append((phase or "none", tally(ids, requirements)))
    lines += table("Phase", phase_rows)
    lines += ["", "## Peer bars", "",
              "Outside tools and standards named in each file's Basis and Target columns: known tool names "
              "first, then the link texts of cited sources.", ""]
    for name in sorted(by_file):
        named = peers(by_file[name], requirements)
        lines.append(f"- [{titles.get(name, name)}]({name}): " + ("; ".join(named) if named else "none named"))
    met_unchecked = [r for r in all_ids if requirements[r]["now"] == "Met" and r not in trace]
    traced_no = [r for r in all_ids if requirements[r]["now"] == "No" and r in trace]
    lines += ["", f"## Met without a checker ({len(met_unchecked)})", "",
              "Marked Met in the Now column, but no test declares `Verifies:` for them.", ""]
    lines += [f"- {r} ({requirements[r]['file']})" for r in met_unchecked] or ["None."]
    lines += ["", f"## Traced but marked No ({len(traced_no)})", "",
              "A test declares `Verifies:` for them while the Now column says No; the Now column may be stale.", ""]
    lines += [f"- {r} ({requirements[r]['file']}): {tests(trace[r])}" for r in traced_no] or ["None."]
    return "\n".join(lines) + "\n"


def tests(where: list[str], limit: int = 3) -> str:
    names = sorted(set(where))
    shown = ", ".join(f"`{n}`" for n in names[:limit])
    return shown + (f" and {len(names) - limit} more" if len(names) > limit else "")


def file_titles(requirements: dict[str, dict]) -> dict[str, str]:
    return {name: (rt.REQUIREMENTS / name).read_text(encoding="utf-8").splitlines()[0].removeprefix("# ").strip()
            for name in {i["file"] for i in requirements.values()}}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    args = parser.parse_args()
    requirements = rt.read_requirements()
    trace, _ = rt.read_markers()
    trace = {rid: where for rid, where in trace.items() if rid in requirements}
    text = render(requirements, trace, file_titles(requirements))
    if args.check:
        if not SCORECARD.exists() or SCORECARD.read_text(encoding="utf-8") != text:
            print("docs/requirements/SCORECARD.md is stale; run scripts/requirement_scorecard.py", file=sys.stderr)
            return 1
        return 0
    SCORECARD.write_text(text, encoding="utf-8")
    print(f"scorecard written for {len(requirements)} requirements", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
