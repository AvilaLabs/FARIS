"""The known-issues page, generated from the defect log (requirement QA-082).

    python3 scripts/known_issues.py            # write docs/KNOWN_ISSUES.md
    python3 scripts/known_issues.py --check    # fail if the page differs from a fresh generation

The source is docs/defects/faris-defects.json (linted by scripts/defect_log.py). The page lists every open
defect first, then the defects that affected a released version and have been fixed, then those found before a
release and fixed before it (kept for the record). Severity words follow docs/defects/README.md. The page
carries no date of its own, so it changes only when the log does and `--check` is stable.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = Path("docs") / "defects" / "faris-defects.json"
PAGE = Path("docs") / "KNOWN_ISSUES.md"
MEANING = {
    "S1": "a wrong physics answer without a warning",
    "S2": "a wrong answer with a warning, or loss of user work or data",
    "S3": "a function fails or misleads, but the user is told or a workaround exists",
    "S4": "cosmetic",
}


def cell(text: str) -> str:
    return " ".join(str(text).replace("|", "/").split())


def table(rows: list[dict], columns: tuple[str, ...]) -> list[str]:
    if not rows:
        return ["None."]
    out = ["| " + " | ".join(c.capitalize() for c in columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    for d in rows:
        values = {
            "id": d["id"], "severity": d["severity"], "title": d["title"], "found": d["found"],
            "affected": ", ".join(d["affected_versions"]),
            "fixed in": d.get("fixed_in") or "not fixed", "what happened": d["disposition"],
        }
        out.append("| " + " | ".join(cell(values[c]) for c in columns) + " |")
    return out


def render(defects: list[dict]) -> str:
    key = lambda d: (d["severity"], d["id"])  # noqa: E731
    open_ = sorted((d for d in defects if d["status"] == "open"), key=key)
    wont = sorted((d for d in defects if d["status"] == "wont-fix"), key=key)
    released = sorted((d for d in defects if d["status"] == "fixed" and d["affected_versions"] != ["unreleased"]), key=key)
    unreleased = sorted((d for d in defects if d["status"] == "fixed" and d["affected_versions"] == ["unreleased"]), key=key)
    lines = [
        "<!-- kind: reference -->",
        "# Known issues",
        "",
        "<!-- Generated by scripts/known_issues.py from docs/defects/faris-defects.json. Do not edit by hand. -->",
        "",
        "Problems in FARIS itself that we know about. This page is generated from the project's defect log, so it is",
        "as current as the log. Limits of what the demo models are on the [limitations page](guide/limitations.md), and",
        "problems in other programs FARIS drives are in [upstream defect drafts](defects/README.md).",
        "",
        "Severity: " + "; ".join(f"**{k}** {v}" for k, v in MEANING.items()) + ".",
        "",
        f"{len(open_)} open, {len(wont)} will not be fixed, {len(released)} fixed that affected a released version, "
        f"{len(unreleased)} fixed before they reached a release.",
        "",
        "## Open",
        "",
        *table(open_, ("id", "severity", "title", "found", "affected", "what happened")),
        "",
        "## Will not be fixed",
        "",
        *table(wont, ("id", "severity", "title", "affected", "what happened")),
        "",
        "## Fixed, and affected a released version",
        "",
        *table(released, ("id", "severity", "title", "affected", "fixed in", "what happened")),
        "",
        "## Fixed before a release",
        "",
        "These were found in development and never shipped.",
        "",
        *table(unreleased, ("id", "severity", "title", "fixed in")),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    defects = json.loads((args.root / LOG).read_text(encoding="utf-8"))["defects"]
    text = render(defects)
    page = args.root / PAGE
    if args.check:
        if not page.is_file() or page.read_text(encoding="utf-8") != text:
            print(f"{PAGE} is out of date; run python3 scripts/known_issues.py", file=sys.stderr)
            return 1
        print(f"known issues: PASS, {PAGE} is current")
        return 0
    page.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
