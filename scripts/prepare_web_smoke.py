"""Make an isolated browser-smoke tree with explicit test-only demo data.

The production web artifact remains untouched.  The synthetic fixture must be
generated by the typed faris-engine test fixture and identify itself in its
manifest before it can replace demo files in the smoke-only copy.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil


def prepare(dist: Path, fixture: Path, output: Path) -> None:
    dist = dist.resolve(strict=True)
    fixture = fixture.resolve(strict=True)
    output = output.resolve()

    def overlaps(first: Path, second: Path) -> bool:
        return first == second or first in second.parents or second in first.parents

    if not dist.is_dir() or not fixture.is_dir():
        raise ValueError("the production dist and synthetic fixture must be directories")
    if output.exists():
        raise FileExistsError(f"refusing to replace existing smoke output: {output}")
    if overlaps(dist, fixture) or overlaps(output, dist) or overlaps(output, fixture):
        raise ValueError("production dist, synthetic fixture, and smoke output must be separate trees")

    manifest_path = fixture / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema") != "faris-web-demo/v1" or manifest.get("fixture_kind") != "synthetic-ci-smoke":
        raise ValueError("the browser smoke fixture must be typed and explicitly marked synthetic-ci-smoke")
    core = manifest.get("core")
    if not isinstance(core, list) or not any(
        isinstance(file, dict) and file.get("path") == "operating-assumptions.json"
        for file in core
    ):
        raise ValueError("the synthetic browser smoke fixture is missing its core files or assumptions")
    for file in core:
        if not isinstance(file, dict) or not isinstance(file.get("path"), str):
            raise ValueError("the synthetic browser smoke fixture has a malformed core inventory")
        relative = Path(file["path"])
        if relative.is_absolute() or ".." in relative.parts or not relative.parts:
            raise ValueError(f"the synthetic browser smoke fixture is missing a safe core file: {relative}")
        source = (fixture / relative).resolve()
        if fixture not in source.parents or not source.is_file():
            raise ValueError(f"the synthetic browser smoke fixture is missing a safe core file: {relative}")
        if source.stat().st_size != file.get("bytes"):
            raise ValueError(f"the synthetic browser smoke fixture has an incorrect size for {relative}")
        declared = file.get("sha256")
        actual = f"sha256:{hashlib.sha256(source.read_bytes()).hexdigest()}"
        if declared != actual:
            raise ValueError(f"the synthetic browser smoke fixture digest differs for {relative}")
    expected = {
        f"{pair}/bundles/{variant}.transport-bundle.json"
        for pair in ("port", "control")
        for variant in ("reference", "breeder-emphasis")
    }
    actual = {file["path"] for file in core if isinstance(file, dict) and isinstance(file.get("path"), str)}
    if not expected <= actual:
        raise ValueError("the synthetic browser smoke fixture needs four paired current replay bundles")
    shutil.copytree(dist, output)
    demo = output / "demo"
    if demo.exists():
        shutil.rmtree(demo)
    shutil.copytree(fixture, demo)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dist", type=Path, help="completed production web dist; it is copied, never modified")
    parser.add_argument("fixture", type=Path, help="test-generated synthetic demo fixture directory")
    parser.add_argument("output", type=Path, help="new isolated synthetic smoke tree")
    args = parser.parse_args()
    prepare(args.dist, args.fixture, args.output)
