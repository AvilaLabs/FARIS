def render_archival_version_metadata(commit_hash: str) -> str:
    """Render OpenMC's supported archival-file fallback for this patch build."""
    if not re.fullmatch(r"[0-9a-f]{40}", commit_hash):
        raise ValueError("OpenMC base commit must be a full 40-character lowercase SHA-1")
    return (
        "# Generated by FARIS from a verified OpenMC source snapshot; do not copy into source.\n"
        f"commit: {commit_hash}\n"
        f"describe-name: {ARCHIVAL_DESCRIBE_NAME}\n"
    )


def verify_generated_version_header(text: str, expected_commit: str) -> dict[str, object]:
    patterns = {
        "major": r"VERSION_MAJOR \{(\d+)\};",
        "minor": r"VERSION_MINOR \{(\d+)\};",
        "release": r"VERSION_RELEASE \{(\d+)\};",
        "development": r"VERSION_DEV \{(true|false)\};",
        "commit_hash": r'VERSION_COMMIT_HASH = "([0-9a-f]+)";',
        "commit_count": r'VERSION_COMMIT_COUNT = "([^"]*)";',
    }
    values: dict[str, str] = {}
    for name, pattern in patterns.items():
        match = re.search(pattern, text)
        if match is None:
            raise RuntimeError(f"configured OpenMC version header is missing {name}")
        values[name] = match.group(1)
    result = {
        "major": int(values["major"]),
        "minor": int(values["minor"]),
        "release": int(values["release"]),
        "development": values["development"] == "true",
        "commit_hash": values["commit_hash"],
        "commit_count": values["commit_count"],
    }
    if (result["major"], result["minor"], result["release"]) != (0, 15, 3):
        raise RuntimeError(f"configured OpenMC source version is not 0.15.3: {result}")
    if result["development"] or result["commit_count"]:
        raise RuntimeError(f"archival metadata unexpectedly indicates a dev build: {result}")
    if result["commit_hash"] != expected_commit:
        raise RuntimeError(f"configured OpenMC commit differs from the verified source base: {result}")
    return result


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_manifest(root: Path) -> list[dict[str, object]]:
    excluded = {".git", "build", "install", "__pycache__"}
    entries: list[dict[str, object]] = []
    for directory, names, filenames in os.walk(root):
        current = Path(directory)
        kept_names = []
        for name in sorted(names):
            path = current / name
            if name in excluded:
                continue
            if path.is_symlink():
                entries.append({
                    "path": path.relative_to(root).as_posix(),
                    "kind": "symlink",
                    "target": os.readlink(path),
                })
                continue
            kept_names.append(name)
        names[:] = kept_names
        for filename in sorted(filenames):
            if filename == ".git":
                continue
            path = current / filename
            relative = path.relative_to(root).as_posix()
            if path.is_symlink():
                entries.append({"path": relative, "kind": "symlink", "target": os.readlink(path)})
            elif path.is_file():
                entries.append({"path": relative, "kind": "file", "sha256": sha256_file(path)})
    return entries


def manifest_digest(manifest: list[dict[str, object]]) -> str:
    body = json.dumps(manifest, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return sha256_bytes(body.encode("utf-8"))


def run(command: list[str], *, cwd: Path | None = None, env: dict[str, str] | None = None,
        log: Path | None = None) -> str:
    if log is None:
        result = subprocess.run(command, cwd=cwd, env=env, check=True, text=True,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        return result.stdout.rstrip()
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("wb") as stream:
        subprocess.run(command, cwd=cwd, env=env, check=True, stdout=stream,
                       stderr=subprocess.STDOUT)
    return str(log)


def require_free_space(path: Path, minimum_bytes: int, stage: str) -> int:
    free = shutil.disk_usage(path).free
    if free < minimum_bytes:
        raise RuntimeError(
            f"refusing {stage}: {free / 1024**3:.2f} GiB free; "
            f"required at least {minimum_bytes / 1024**3:.2f} GiB"
        )
    return free


