def read_case(openmc, case_dir: Path, names: list[str], n_batches: int) -> dict:
    """Per-bin mean, relative error, batch values and run time for every spike tally of one run."""
    import numpy as np
    files = {int(p.name.split(".")[1]): p for p in case_dir.glob("statepoint.*.h5")}
    require(sorted(files) == list(range(1, n_batches + 1)), f"{case_dir}: statepoints do not cover batches 1..{n_batches}")
    cumulative = {n: [] for n in names}
    for b in range(1, n_batches + 1):
        with openmc.StatePoint(str(files[b])) as sp:
            require(int(sp.current_batch) == b and int(sp.n_realizations) == b, f"{case_dir}: bad realization count at batch {b}")
            for n in names:
                cumulative[n].append(sp.get_tally(name=n).sum.ravel().copy())
    with openmc.StatePoint(str(files[n_batches])) as sp:
        require(tuple(int(v) for v in sp.version) == (0, 15, 3), "statepoint version is not 0.15.3")
        require(sp.run_mode == "fixed source", "statepoint is not fixed source")
        sim_seconds = sp.runtime.get("simulation")
        require(sim_seconds is not None and sim_seconds > 0, "statepoint carries no simulation run time")
        result = {"simulation_seconds": float(sim_seconds), "histories": int(sp.n_particles) * n_batches, "batches": n_batches, "tallies": {}}
        for n in names:
            tally = sp.get_tally(name=n)
            mean, std = tally.mean.ravel(), tally.std_dev.ravel()
            cum = np.array(cumulative[n])
            per_batch = np.vstack([cum[0], np.diff(cum, axis=0)])
            require(np.allclose(per_batch.mean(axis=0), mean, rtol=1e-9, atol=1e-300), f"{n}: batch values disagree with the statepoint mean")
            with np.errstate(divide="ignore", invalid="ignore"):
                rel = np.where(mean > 0, std / mean, np.nan)
            result["tallies"][n] = {"mean": mean, "rel_err": rel, "vov": variance_of_variance(per_batch)}
    for p in files.values():
        if p.name != f"statepoint.{n_batches}.h5":
            p.unlink(missing_ok=True)
    return result


def summarise(analog: dict, windowed: dict) -> dict:
    import numpy as np

    def stats(entry, seconds):
        mean, rel, vov = entry["mean"], entry["rel_err"], entry["vov"]
        scored = np.isfinite(rel)
        peak = int(np.nanargmax(np.where(scored, mean, np.nan))) if scored.any() else None
        fom = np.where(scored & (rel > 0), 1.0 / (rel ** 2 * seconds), np.nan)
        def q(a, p):
            a = a[np.isfinite(a)]
            return float(np.percentile(a, p)) if a.size else None
        return {"bins": int(mean.size), "bins_scored": int(scored.sum()), "peak_bin": peak,
                "peak_mean": None if peak is None else float(mean[peak]), "peak_rel_err": None if peak is None else float(rel[peak]),
                "peak_vov": None if peak is None else (None if not np.isfinite(vov[peak]) else float(vov[peak])),
                "rel_err_median": q(rel, 50), "rel_err_p90": q(rel, 90), "rel_err_max": q(rel, 100),
                "fraction_rel_err_below_10pct": float((rel[scored] < 0.1).mean()) if scored.any() else None,
                "vov_median": q(vov, 50), "vov_p90": q(vov, 90), "fom_median": q(fom, 50), "fom_peak_bin": None if peak is None else (None if not np.isfinite(fom[peak]) else float(fom[peak]))}

    out = {}
    for name in analog["tallies"]:
        a, w = stats(analog["tallies"][name], analog["simulation_seconds"]), stats(windowed["tallies"][name], windowed["simulation_seconds"])
        ratio = None
        if a["fom_median"] and w["fom_median"]:
            ratio = w["fom_median"] / a["fom_median"]
        out[name] = {"analog": a, "weight_windowed": w, "fom_median_ratio_ww_over_analog": ratio}
    return out


def command_compare(args) -> int:
    require(args.i_have_the_cpu, "compare runs two continuous-energy transport calculations on many cores; pass --i-have-the-cpu to run it")
    import numpy as np
    openmc = import_openmc()
    record_path = Path(args.generate_record).expanduser().resolve(strict=True)
    record = json.loads(record_path.read_text(encoding="utf-8"))
    ww_file = Path(record["weight_windows_file"])
    require(ww_file.is_file() and sha256(ww_file) == record["weight_windows_sha256"], "weight_windows.h5 does not match the hash in the generate record")
    input_path = Path(args.input).expanduser().resolve(strict=True)
    require(sha256(input_path) == record["input_sha256"], "input.json differs from the one the windows were generated for")
    inp = RT.read_input(input_path)
    exe = Path(inp["openmc_executable"]).expanduser().resolve(strict=True)
    work = fresh_dir(Path(args.work_dir) / "compare")
    build = build_spike(inp, work / "build", openmc)
    model = build["model"]
    names = build["tally_names"]
    particles = int(args.particles_per_batch)

    def run_case(label, batches, windows, per_batch):
        case = work / label
        case.mkdir()
        s = model.settings
        s.batches, s.particles, s.seed = int(batches), particles, int(args.seed)
        s.statepoint = {"batches": list(range(1, int(batches) + 1))} if per_batch else {"batches": [int(batches)]}
        s.weight_windows_on = windows
        s.weight_windows_file = str(ww_file) if windows else None
        model.export_to_xml(directory=str(case))
        wall = run_openmc(exe, case, args.threads)
        return case, wall

    case, _ = run_case("analog", args.batches, False, True)
    analog = read_case(openmc, case, names, int(args.batches))
    match = {"mode": args.match, "analog_batches": int(args.batches)}
    ww_batches = int(args.batches)
    if args.match == "wall-time":
        times = {}
        for b in (2, 4):
            pilot, _ = run_case(f"pilot-ww-{b}", b, True, False)
            with openmc.StatePoint(str(pilot / f"statepoint.{b}.h5")) as sp:
                times[b] = float(sp.runtime["simulation"])
        slope = (times[4] - times[2]) / 2.0
        require(slope > 0, "pilot runs gave no positive per-batch time")
        intercept = times[2] - 2.0 * slope
        ww_batches = int(math.floor((analog["simulation_seconds"] - intercept) / slope))
        require(ww_batches >= 10, f"equal-wall-time weight-windowed run would have only {ww_batches} batches; the analog run is too short")
        match.update({"pilot_seconds": times, "seconds_per_batch": slope, "overhead_seconds": intercept})
    match["weight_windowed_batches"] = ww_batches
    case, _ = run_case("weight-windowed", ww_batches, True, True)
    windowed = read_case(openmc, case, names, ww_batches)
    report = {
        "schema_version": SCHEMA, "kind": "compare", "openmc_version": openmc.__version__,
        "input_sha256": record["input_sha256"], "generate_record": str(record_path),
        "weight_windows_sha256": record["weight_windows_sha256"], "generation_parameters": record["parameters"],
        "match": match, "particles_per_batch": particles, "seed": int(args.seed),
        "histories": {"analog": analog["histories"], "weight_windowed": windowed["histories"]},
        "simulation_seconds": {"analog": analog["simulation_seconds"], "weight_windowed": windowed["simulation_seconds"]},
        "summary": summarise(analog, windowed),
        "per_bin": {n: {"analog": {k: np.where(np.isfinite(v), v, np.nan).tolist() for k, v in analog["tallies"][n].items()},
                        "weight_windowed": {k: np.where(np.isfinite(v), v, np.nan).tolist() for k, v in windowed["tallies"][n].items()}} for n in names},
        "note": "FOM = 1 / (relative_error^2 * simulation_seconds) per bin; NaN (JSON null after json.dumps allow_nan) marks bins with no score",
    }
    text = json.dumps(report, indent=2, sort_keys=True, allow_nan=True).replace("NaN", "null")
    (work / "compare-report.json").write_text(text + "\n", encoding="utf-8")
    print(json.dumps({k: report[k] for k in ("match", "histories", "simulation_seconds", "summary")}, indent=2, sort_keys=True).replace("NaN", "null"))
    return 0


