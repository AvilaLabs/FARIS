#!/usr/bin/env python3
"""FW-CADIS weight-window spike for the 0.2 test run.

Question: do FW-CADIS weight windows generated by a random-ray multigroup pass
and applied to the continuous-energy OpenMC model cut the sampling error of the
magnet peak and the vessel/magnet spectra, measured against the analog run of
the same model (docs/DEMO_ROADMAP.md, "Magnet peak with FW-CADIS weight
windows" and "Decisions for 0.2")?

The model is the FARIS adapter's own: this script imports
integrations/openmc/reactor_transport.py and calls its check_data_identity()
and compose() on a FARIS request input.json, so geometry, materials, source and
settings are the adapter's, not a reimplementation. The adapter is unchanged.
It then replaces the tallies with the spike's own and turns photon transport
off (neutron-only comparison; the adapter's heating responses are not part of
this question).

Subcommands (each writes into a fresh subdirectory of --work-dir):

  build      export the adapter model and the spike model, report the tallies
  mgxs-plan  write the multigroup + random-ray + weight-window configuration as
             JSON (nothing is executed)
  generate   run MGXS generation, the random-ray solve and write
             weight_windows.h5 (needs --i-have-the-cpu)
  compare    run the analog and the weight-windowed continuous-energy model and
             report per-bin relative error, variance of the variance and figure
             of merit (needs --i-have-the-cpu)

`generate` and `compare` run OpenMC for a long time on many cores; they refuse
to start without --i-have-the-cpu.
"""

