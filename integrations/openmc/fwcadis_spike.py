def load_709_bounds(path: Path = ACTINV_709G):
    """The 710 fispact-709 group boundaries in eV, ascending."""
    import numpy as np
    bounds = np.load(path)["bounds"]
    require(bounds.shape == (710,), f"expected 710 bounds, got {bounds.shape}")
    require(bool(np.all(np.diff(bounds) > 0)), "709-group bounds are not strictly increasing")
    return bounds


def select_variant(inp: dict) -> dict:
    variant = next((v for v in inp["manifest"]["variants"] if v["id"] == inp["physics"]["variant_id"]), None)
    require(variant is not None, "physics variant missing from manifest")
    return variant


def component(variant: dict, component_id: str) -> dict:
    found = next((c for c in variant["components"] if c["id"] == component_id), None)
    require(found is not None, f"variant has no component {component_id}")
    return found


def r9(values: list[float]) -> list[float]:
    """Round away binary noise (1e-9 m) so extents read as the numbers they mean."""
    return [round(float(v), 9) for v in values]


def peak_mesh_extents(manifest: dict, variant: dict, dims: tuple[int, int, int] = OUTBOARD_DIMS) -> dict:
    """Outboard peak mesh behind the port and the matching inboard slab, in metres.

    The torus axis is y and the port is centred on toroidal angle 0 (the +x
    axis), so on the midplane the magnets layer spans R0 + [a, b] outboard and
    R0 - [b, a] inboard (a, b = inner and outer minor radius of the magnets).
    Transverse extent: the penetration prism's y and z bounds if the manifest
    has one, otherwise +-PORT_HALF_WIDTH_M (see the constant). The mesh is
    axis-aligned, so over the transverse half-width w the magnets' curved
    surfaces lie within R0 + a - 0.0005 .. R0 + b (for w = 0.15 m): the box
    slightly over-covers the layer by under 1 mm and is otherwise inside it.
    """
    R = float(manifest["major_radius_m"])
    magnets = component(variant, "magnets")
    a, b = float(magnets["inner_minor_radius_m"]), float(magnets["outer_minor_radius_m"])
    require(0.0 < a < b < R, "magnets layer radii must satisfy 0 < inner < outer < R0")
    penetration = manifest.get("penetration")
    if penetration is not None:
        bounds = penetration["bounds_m"]
        lo, hi = bounds["minimum_xyz_m"], bounds["maximum_xyz_m"]
        y, z = [float(lo[1]), float(hi[1])], [float(lo[2]), float(hi[2])]
        source = "penetration bounds_m y,z"
    else:
        y = z = [-PORT_HALF_WIDTH_M, PORT_HALF_WIDTH_M]
        source = f"+-{PORT_HALF_WIDTH_M} m (port-reference prism half width)"
    return {
        "outboard": {"lower_left_m": r9([R + a, y[0], z[0]]), "upper_right_m": r9([R + b, y[1], z[1]]), "dimensions": list(dims)},
        "inboard": {"lower_left_m": r9([R - b, y[0], z[0]]), "upper_right_m": r9([R - a, y[1], z[1]]), "dimensions": list(dims)},
        "derivation": {
            "major_radius_m": R,
            "magnets_inner_minor_radius_m": a,
            "magnets_outer_minor_radius_m": b,
            "transverse_extent_source": source,
            "toroidal_angle_of_port_centre_rad": 0.0,
        },
    }


def ww_mesh_extents(manifest: dict, variant: dict, cell_m: float = WW_CELL_M) -> dict:
    """Weight-window mesh: the whole torus, so windows exist wherever a particle goes."""
    R = float(manifest["major_radius_m"])
    outer = float(variant["components"][-1]["outer_minor_radius_m"])
    half_xz = math.ceil((R + outer + WW_MARGIN_M) / cell_m) * cell_m
    half_y = math.ceil((outer + WW_MARGIN_M) / cell_m) * cell_m
    dims = [round(2 * half_xz / cell_m), round(2 * half_y / cell_m), round(2 * half_xz / cell_m)]
    return {"lower_left_m": r9([-half_xz, -half_y, -half_xz]), "upper_right_m": r9([half_xz, half_y, half_xz]), "dimensions": dims, "cell_m": cell_m}


def source_group(edges_ev: list[float], energy_ev: float) -> dict:
    """The one random-ray group holding the source energy. Group 1 is the highest energy."""
    require(edges_ev[0] < energy_ev < edges_ev[-1], "source energy outside the group structure")
    n = len(edges_ev) - 1
    for i in range(n):
        if edges_ev[i] <= energy_ev < edges_ev[i + 1]:
            return {"group_index_1_based_high_to_low": n - i, "lower_ev": edges_ev[i], "upper_ev": edges_ev[i + 1], "source_energy_ev": energy_ev}
    raise RuntimeError("unreachable")


def variance_of_variance(batch_values):
    """Per-bin VOV from batch values, shape (n_batches, n_bins): sum d^4 / (sum d^2)^2 - 1/n.

    Bins with no scores (zero denominator) give NaN.
    """
    import numpy as np
    x = np.asarray(batch_values, dtype=float)
    n = x.shape[0]
    d = x - x.mean(axis=0)
    s2 = (d ** 2).sum(axis=0)
    s4 = (d ** 4).sum(axis=0)
    with np.errstate(divide="ignore", invalid="ignore"):
        vov = s4 / s2 ** 2 - 1.0 / n
    return np.where(s2 > 0, vov, np.nan)


