def run_openmc(exe: Path, cwd: Path, threads: int) -> float:
    """Run the solver in cwd; return wall seconds. Fails closed on exit code or lost particles."""
    env = os.environ.copy()
    env["OMP_NUM_THREADS"] = str(threads)
    env.setdefault("OPENBLAS_NUM_THREADS", "1")
    env["PATH"] = str(exe.parent) + os.pathsep + env.get("PATH", "")
    start = time.monotonic()
    with (cwd / "openmc.stdout.log").open("wb") as out, (cwd / "openmc.stderr.log").open("wb") as err:
        code = subprocess.run([str(exe)], cwd=cwd, env=env, stdout=out, stderr=err, check=False).returncode
    wall = time.monotonic() - start
    require(code == 0, f"OpenMC exited {code}; see {cwd}/openmc.stderr.log")
    log = (cwd / "openmc.stdout.log").read_bytes() + b"\n" + (cwd / "openmc.stderr.log").read_bytes()
    require(not re.search(rb"(?i)particle\s+\d+\s+was lost|lost particles?", log), "OpenMC reported lost particles")
    return wall


