def rr_tallies(openmc, build: dict, edges_ev: list[float]):
    """Flux-only tallies that define the FW-CADIS objective.

    Random ray accepts only flux/total/fission/nu-fission/events scores and
    cell/cell_instance/distribcell/energy/material/mesh/universe filters, so
    the particle filter of the continuous-energy tallies is dropped (strings in
    libopenmc.so; the solver source is not shipped). Energy filters use group
    edges: the fast-flux filter is [0.1 MeV, 20 MeV], the component filters
    the whole structure.
    """
    cells = build["parts"]["component_cells"]
    fast = openmc.EnergyFilter([FAST_FLUX_LOWER_EV, edges_ev[-1]])
    full = openmc.EnergyFilter(edges_ev)
    tallies = openmc.Tallies()
    for side in ("outboard", "inboard"):
        t = openmc.Tally(name=f"rr-peak-{side}-fast-flux")
        t.filters = [openmc.MeshFilter(build["meshes"][side]), fast]
        t.scores = ["flux"]
        tallies.append(t)
    for cid in SPECTRUM_COMPONENTS:
        t = openmc.Tally(name=f"rr-{cid}-flux")
        t.filters = [openmc.CellFilter(cells[cid]), full]
        t.scores = ["flux"]
        tallies.append(t)
    return tallies


def configure_random_ray(openmc, model, ww_mesh, params: dict, edges_ev: list[float], rr_tally_set, ray_box_cm, subdivide_domains):
    """Put the random-ray and FW-CADIS settings on a (multigroup) model.

    Every key is one OpenMC 0.15.3 validates in Settings.random_ray
    (settings.py:1302-1347, documented 180-225) or a plain Settings attribute.
    """
    settings = model.settings
    settings.energy_mode = "multi-group"
    settings.run_mode = "fixed source"
    settings.photon_transport = False
    settings.batches = int(params["batches"])
    settings.inactive = int(params["inactive"])
    settings.particles = int(params["rays"])  # rays per batch in random-ray mode (model.py:2233)
    settings.seed = int(params["seed"])
    settings.statepoint = {}
    lower, upper = ray_box_cm
    settings.random_ray = {
        "distance_inactive": float(params["distance_inactive_cm"]),
        "distance_active": float(params["distance_active_cm"]),
        "ray_source": openmc.IndependentSource(space=openmc.stats.Box(lower, upper)),
        "volume_estimator": params["volume_estimator"],
        "source_shape": params["source_shape"],
        "adjoint": False,  # FW-CADIS runs its own forward then adjoint solve; the flag is for a pure adjoint run
        "sample_method": params["sample_method"],
        "diagonal_stabilization_rho": float(params["diagonal_stabilization_rho"]),
        "source_region_meshes": [(ww_mesh, subdivide_domains)],
    }
    model.tallies = rr_tally_set
    settings.weight_window_generators = [openmc.WeightWindowGenerator(
        mesh=ww_mesh, energy_bounds=list(edges_ev), particle_type="neutron", method="fw_cadis",
        max_realizations=int(params["batches"]),  # as in the OpenMC random-ray example: update once, at the end
    )]


def subdivision_domains(model):
    """Non-void materials plus null-filled cells: disjoint, so no source region gets two meshes."""
    domains = list(model.materials)
    domains += [c for c in model.geometry.root_universe.cells.values() if c.fill is None]
    return domains


