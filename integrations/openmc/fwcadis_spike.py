def adapter_model(inp: dict, adapter_dir: Path, openmc):
    """The adapter's compose(), called exactly as reactor_transport.main() does."""
    xml = Path(inp["cross_sections"]).expanduser().resolve(strict=True)
    os.environ["OPENMC_CROSS_SECTIONS"] = str(xml)
    inp = copy.deepcopy(inp)
    # A port request would sample 1M points in Python for volumes this spike
    # never uses; the adapter's minimum is enough.
    if inp["manifest"].get("penetration") is not None:
        inp["penetration_volume_samples"] = 100_000
    coupled = any(r["score"]["kind"] == "heating" for r in inp["request"]["responses"])
    _, _, _, runtime_temperature, _, photon_physics = RT.check_data_identity(inp["physics"], xml, openmc, coupled)
    result = RT.compose(inp, adapter_dir, openmc, runtime_temperature, photon_physics)
    keys = ("model", "response_by_tally", "mesh_tally", "mesh_defs", "volumes_cm3", "volume_se_cm3", "whole_cm3", "mesh_bin_cm3",
            "component_cells", "spectrum_tallies", "plasma", "mesh_index_audit", "penetration_volume_audit", "geometry_audit", "region_volumes_cm3")
    return dict(zip(keys, result)), inp


def regular_mesh(openmc, spec: dict, name: str):
    mesh = openmc.RegularMesh(name=name)
    mesh.dimension = tuple(spec["dimensions"])
    mesh.lower_left = [100.0 * v for v in spec["lower_left_m"]]
    mesh.upper_right = [100.0 * v for v in spec["upper_right_m"]]
    return mesh


def build_spike(inp: dict, work: Path, openmc, dims: tuple[int, int, int] = OUTBOARD_DIMS) -> dict:
    """Adapter model plus the spike's tallies. Exports adapter and spike XML."""
    parts, inp = adapter_model(inp, work / "adapter-export", openmc)
    model = parts["model"]
    manifest = inp["manifest"]
    variant = select_variant(inp)
    cells = parts["component_cells"]
    for cid in SPECTRUM_COMPONENTS:
        require(cid in cells, f"scenario has no component {cid}")
    extents = peak_mesh_extents(manifest, variant, dims)
    bounds = load_709_bounds()
    energy_fast = openmc.EnergyFilter([FAST_FLUX_LOWER_EV, FAST_FLUX_UPPER_EV])
    neutron = openmc.ParticleFilter("neutron")
    tallies = openmc.Tallies()
    meshes = {}

    def add(name, filters, scores=("flux",)):
        tally = openmc.Tally(name=name)
        tally.filters = filters
        tally.scores = list(scores)
        tally.estimator = "tracklength"
        tallies.append(tally)
        return tally

    for side in ("outboard", "inboard"):
        spec = extents[side]
        fine = regular_mesh(openmc, spec, f"peak-{side}")
        meshes[side] = fine
        add(f"peak-{side}-fast-flux", [openmc.MeshFilter(fine), energy_fast, neutron])
        whole = regular_mesh(openmc, {**spec, "dimensions": [1, 1, 1]}, f"peak-{side}-mean")
        add(f"peak-{side}-fast-flux-mean", [openmc.MeshFilter(whole), energy_fast, neutron])
    spectrum_filter = openmc.EnergyFilter(bounds)
    for cid in SPECTRUM_COMPONENTS:
        add(f"spectrum-709-{cid}", [openmc.CellFilter(cells[cid]), neutron, spectrum_filter])
        add(f"fast-flux-{cid}", [openmc.CellFilter(cells[cid]), energy_fast, neutron])
    model.tallies = tallies
    settings = model.settings
    settings.photon_transport = False
    settings.statepoint = {}
    spike_dir = work / "spike-export"
    spike_dir.mkdir()
    model.export_to_xml(directory=str(spike_dir))
    return {"model": model, "parts": parts, "inp": inp, "extents": extents, "meshes": meshes, "tally_names": [t.name for t in tallies],
            "adapter_dir": work / "adapter-export", "spike_dir": spike_dir, "variant": variant}


def xml_hashes(directory: Path) -> dict[str, str]:
    return {p.name: sha256(p) for p in sorted(directory.glob("*.xml"))}


def void_report(parts: dict) -> dict:
    """Random ray needs void as a null-filled cell; the adapter already does this."""
    cells = parts["model"].geometry.get_all_cells().values()
    void_cells = sorted(c.name for c in cells if c.fill is None)
    require(void_cells, "no null-filled void cells found")
    require(not any(m.density == 0.0 for m in parts["model"].materials), "a zero-density material is present")
    return {"adapter_source": "reactor_transport.compose(): void recipe -> materials[id] = None, cells filled with None",
            "null_filled_cells": void_cells}


