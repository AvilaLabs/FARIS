TEMPLATE = Path(__file__).resolve().parents[2] / "crates/faris-model/tests/fixtures/design/pass.faris-design.json"
HISTORY = TEMPLATE.with_name("pass.operating-history.json")


def design_for(step: Path, inspection: dict, unit: str, break_material: str | None) -> dict:
    value = json.loads(TEMPLATE.read_text())
    templates = value["solids"]
    solids = []
    for i, s in enumerate(inspection["solids"]):
        t = copy.deepcopy(templates[1 + (i % 2)] if i else templates[0])
        t["id"] = (s.get("step_name") or f"solid-{i}").lower().replace("_", "-")
        t["step_index"] = s["step_index"]
        t["step_name"] = s.get("step_name")
        t["fingerprint"] = {"cad_volume_m3": s["cad_volume_m3"], "centroid_m": s["centroid_m"]}
        solids.append(t)
    solids[0]["role"] = "plasma_chamber"
    solids[0]["material_id"] = "void"
    solids[0]["replacement_group_id"] = None
    for t in solids[1:]:
        t["role"] = "first_wall"
        t["material_id"] = "tungsten"
        t["replacement_group_id"] = None
    value["solids"] = solids
    value["replacement_groups"] = []
    value["cad"]["step_file"] = step.name
    value["cad"]["step_sha256"] = sha256_file(step)
    value["cad"]["length_unit"] = unit
    value["plasma"]["chamber_solid_id"] = solids[0]["id"]
    value["operating_scenario"] = {"path": HISTORY.name, "sha256": sha256_file(HISTORY)}
    if break_material == "null":
        solids[1]["material_id"] = None
    elif break_material == "unknown":
        solids[1]["material_id"] = "unobtainium"
    return value


# ---------------------------------------------------------------------------
# Generation.

def entry(model_id, family, cls, base, scale, seed, kind, expected, subject, files, chord, extra=None) -> dict:
    out = {
        "id": model_id, "family": family, "class": cls, "base": base, "scale": scale, "seed": seed,
        "kind": kind, "expected_requirements": expected, "subject": subject, "chord_m": chord / 100.0,
        "files": files,
    }
    if extra:
        out.update(extra)
    return out


def hashed(directory: Path, names) -> dict:
    return {n: sha256_file(directory / n) for n in names}


def generate(out: Path, work: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    work.mkdir(parents=True, exist_ok=True)
    models = []
    (out / HISTORY.name).write_bytes(HISTORY.read_bytes())

    def stage(model_id: str) -> Path:
        d = work / model_id
        d.mkdir(parents=True, exist_ok=True)
        return d

    clean_bases: dict[tuple[str, int], Path] = {}
    # Clean models: the imprinted conversion of each base at each scale.
    for base in BASES:
        for si, s in enumerate(SCALES):
            model_id = f"clean-{base}-{si}"
            d = stage(model_id)
            parts = build_parts(base, s)
            step = d / f"{model_id}.step"
            write_step(parts, step)
            chord = chord_cm(base, s, None)
            result = run_conversion(step, parts, d, chord, angular=angular_rad(base))
            if result.get("exit_code") != 0:
                raise SystemExit(f"{model_id}: clean model did not convert: {result}")
            for ext in ("bin", "json"):
                (out / f"{model_id}.facets.{ext}").write_bytes((d / f"model.facets.{ext}").read_bytes())
            clean_bases[(base, si)] = out / model_id
            names = [f"{model_id}.facets.bin", f"{model_id}.facets.json"]
            models.append(entry(model_id, "clean", None, base, s, None, "clean", [], "imprinted", hashed(out, names), chord,
                                {"conversion": {k: result.get(k) for k in ("chord_cm", "timing_seconds")},
                                 "cad_volumes_m3": cad_volumes(step, parts),
                                 "deviation": run_deviation(step, d / "model.facets.bin", parts, d)}))

    # Seeded models.
    for cls, base, si, seed in SEEDED:
        s = SCALES[si]
        model_id = f"seeded-{cls}-{base}"
        d = stage(model_id)
        if cls in MESH_CLASSES:
            model = load_model(clean_bases[(base, si)])
            mutated = MUTATORS[cls](model, random.Random(seed), base)
            src = model["manifest"]["source"]
            save_model(out / model_id, mutated, src["kind"], src["sha256"], 0, model["manifest"].get("implicit_complement_tag"))
            names = [f"{model_id}.facets.bin", f"{model_id}.facets.json"]
            extra = {"mutated_from": f"clean-{base}-{si}"}
            if cls == "zero-volume":
                # The CAD kernel's own answer to a solid of zero volume, recorded for the report.
                cad_parts = build_parts(base, s, "zero-volume")
                cad_step = d / f"{model_id}.step"
                write_step(cad_parts, cad_step)
                (d / "convert").mkdir(exist_ok=True)
                extra["local_run"] = {"convert": run_conversion(cad_step, cad_parts, d / "convert", 0.1, angular=angular_rad(base))}
            models.append(entry(model_id, "mesh", cls, base, s, seed, "seeded", EXPECTED[cls], "imprinted", hashed(out, names),
                                chord_cm(base, s, None), extra))
            continue
        defect = None if cls in ("duplicate-surface", "wrong-units", "missing-material") else cls
        parts = build_parts(base, s, defect)
        step = d / f"{model_id}.step"
        write_step(parts, step)
        chord = chord_cm(base, s, defect)
        record = {}
        if cls in ("wrong-units", "missing-material"):
            import faris_cad
            inspection = faris_cad.inspect_step(step, "mm")
            (out / f"{model_id}.step").write_bytes(step.read_bytes())
            (out / f"{model_id}.inspect.json").write_text(json.dumps(inspection, indent=1) + "\n")
            unit = "m" if cls == "wrong-units" else "mm"
            design = design_for(out / f"{model_id}.step", inspection, unit, "unknown" if cls == "missing-material" and base == "port" else ("null" if cls == "missing-material" else None))
            (out / f"{model_id}.design.json").write_text(json.dumps(design, indent=1) + "\n")
            names = [f"{model_id}.step", f"{model_id}.inspect.json", f"{model_id}.design.json"]
            models.append(entry(model_id, "cad", cls, base, s, seed, "seeded", ["design-check"], "design", hashed(out, names), chord,
                                {"design_check": {"fails_at": 2 if cls == "wrong-units" else 1 if base == "boxes" else 4}}))
            continue
        # Geometry classes: convert (imprinted) where the kernel allows, tessellate (not imprinted) otherwise.
        record["booleans"] = run_booleans(step, len(parts), d)
        if cls in ("overlap", "duplicate-surface"):
            conv_dir = d / "convert"
            conv_dir.mkdir(exist_ok=True)
            record["convert"] = run_conversion(step, parts, conv_dir, chord, angular=angular_rad(base))
            tess_dir = d / "tess"
            tess_dir.mkdir(exist_ok=True)
            record["tessellate"] = run_conversion(step, parts, tess_dir, chord, imprint=False, angular=angular_rad(base))
            if record["tessellate"].get("exit_code") != 0:
                raise SystemExit(f"{model_id}: could not tessellate: {record['tessellate']}")
            subject, source = "unimprinted", tess_dir / "solids"
        else:
            conv_dir = d / "convert"
            conv_dir.mkdir(exist_ok=True)
            record["convert"] = run_conversion(step, parts, conv_dir, chord, angular=angular_rad(base))
            if record["convert"].get("exit_code") == 0:
                subject, source = "imprinted", conv_dir / "model"
            else:
                tess_dir = d / "tess"
                tess_dir.mkdir(exist_ok=True)
                record["tessellate"] = run_conversion(step, parts, tess_dir, chord, imprint=False, angular=angular_rad(base))
                if record["tessellate"].get("exit_code") != 0:
                    subject, source = None, None
                else:
                    subject, source = "unimprinted", tess_dir / "solids"
        names = []
        if source is not None:
            for ext in ("bin", "json"):
                (out / f"{model_id}.facets.{ext}").write_bytes(Path(f"{source}.facets.{ext}").read_bytes())
            names = [f"{model_id}.facets.bin", f"{model_id}.facets.json"]
        extra = {"local_run": record}
        if cls in ("sliver", "misrepresented-sliver") and subject == "imprinted":
            extra["deviation"] = run_deviation(step, conv_dir / "model.facets.bin", parts, d)
        models.append(entry(model_id, "cad", cls, base, s, seed, "seeded", EXPECTED[cls], subject, hashed(out, names), chord, extra))

    index = {"corpus_version": CORPUS_VERSION, "generator": "integrations/cad/faris_corpus.py", "models": models}
    (out / "corpus.json").write_text(json.dumps(index, indent=1) + "\n")


# Small overlaps (GEO-021 asks for detection down to 1e-4 of the smaller solid; 1e-5 is one decade
# below the target). Added to an existing corpus without regenerating it: `generate-overlaps`.
OVERLAP_FRACTIONS = [("1e-4", 1.0e-4), ("1e-5", 1.0e-5)]
OVERLAP_BASES = [("boxes", 0, 151), ("port", 0, 152)]


def seeded_common_volume_m3(base: str, s: float, fraction: float) -> tuple[float, float]:
    """(smaller solid volume, overlap volume) in m3 from the analytic dimensions of `build_parts`."""
    if base == "boxes":
        core = (100.0 * s) ** 3 / (1.0 - fraction)
        return core * 1.0e-9, core * fraction * 1.0e-9
    w, t, radius = 400.0 * s, 100.0 * s, 60.0 * s
    plug = math.pi * radius**2 * t / (1.0 - fraction)
    return plug * 1.0e-9, plug * fraction * 1.0e-9


def generate_overlaps(out: Path, work: Path) -> None:
    import faris_cad
    index = json.loads((out / "corpus.json").read_text())
    ids = {f"seeded-overlap-{base}-{tag}" for base, _si, _seed in OVERLAP_BASES for tag, _f in OVERLAP_FRACTIONS}
    models = [m for m in index["models"] if m["id"] not in ids]
    work.mkdir(parents=True, exist_ok=True)
    for base, si, seed in OVERLAP_BASES:
        s = SCALES[si]
        for tag, fraction in OVERLAP_FRACTIONS:
            model_id = f"seeded-overlap-{base}-{tag}"
            d = work / model_id
            d.mkdir(parents=True, exist_ok=True)
            parts = build_parts(base, s, "overlap", fraction)
            step = d / f"{model_id}.step"
            write_step(parts, step)
            chord = chord_cm(base, s, "overlap")
            record = {"booleans": run_booleans(step, len(parts), d)}
            volumes = faris_cad.inspect_step(step, "mm")["solids"]
            record["solid_volumes_m3"] = [v["cad_volume_m3"] for v in volumes]
            conv_dir = d / "convert"
            conv_dir.mkdir(exist_ok=True)
            record["convert"] = run_conversion(step, parts, conv_dir, chord, angular=angular_rad(base))
            tess_dir = d / "tess"
            tess_dir.mkdir(exist_ok=True)
            record["tessellate"] = run_conversion(step, parts, tess_dir, chord, imprint=False, angular=angular_rad(base))
            if record["tessellate"].get("exit_code") != 0:
                raise SystemExit(f"{model_id}: could not tessellate: {record['tessellate']}")
            for ext in ("bin", "json"):
                (out / f"{model_id}.facets.{ext}").write_bytes(Path(f"{tess_dir / 'solids'}.facets.{ext}").read_bytes())
            names = [f"{model_id}.facets.bin", f"{model_id}.facets.json"]
            smaller, common = seeded_common_volume_m3(base, s, fraction)
            extra = {
                "mutated_from": f"clean-{base}-{si}",
                "seeded_overlap": {
                    "pair": [0, 1], "fraction_of_smaller": fraction,
                    "smaller_solid_volume_m3": smaller, "common_volume_m3": common,
                },
                "local_run": record,
            }
            models.append(entry(model_id, "cad", "overlap", base, s, seed, "seeded", EXPECTED["overlap"], "unimprinted", hashed(out, names), chord, extra))
    index["models"] = models
    (out / "corpus.json").write_text(json.dumps(index, indent=1) + "\n")


def record_cad_volumes(out: Path, work: Path) -> None:
    """Add each clean model's CAD volumes to an existing corpus without regenerating its files."""
    index = json.loads((out / "corpus.json").read_text())
    work.mkdir(parents=True, exist_ok=True)
    for m in index["models"]:
        if m["kind"] != "clean":
            continue
        parts = build_parts(m["base"], m["scale"])
        step = work / f"{m['id']}.step"
        write_step(parts, step)
        m["cad_volumes_m3"] = cad_volumes(step, parts)
    (out / "corpus.json").write_text(json.dumps(index, indent=1) + "\n")


def verify(out: Path) -> int:
    index = json.loads((out / "corpus.json").read_text())
    bad = 0
    for m in index["models"]:
        for name, digest in m["files"].items():
            if sha256_file(out / name) != digest:
                print(f"hash mismatch: {name}")
                bad += 1
        if m["subject"] in ("imprinted", "unimprinted"):
            base = out / m["id"]
            faris_facets.unpack_facets(Path(str(base) + ".facets.bin").read_bytes())
    seeded = [m for m in index["models"] if m["kind"] == "seeded"]
    clean = [m for m in index["models"] if m["kind"] == "clean"]
    classes = {m["class"] for m in seeded}
    print(f"{len(seeded)} seeded models in {len(classes)} classes, {len(clean)} clean models, {bad} problems")
    return 1 if bad else 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--out", type=Path, required=True)
    g.add_argument("--work", type=Path, required=True)
    o = sub.add_parser("generate-overlaps")
    o.add_argument("--out", type=Path, required=True)
    o.add_argument("--work", type=Path, required=True)
    c = sub.add_parser("record-cad-volumes")
    c.add_argument("--out", type=Path, required=True)
    c.add_argument("--work", type=Path, required=True)
    v = sub.add_parser("verify")
    v.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    if args.command == "verify":
        return verify(args.out)
    if args.command == "record-cad-volumes":
        record_cad_volumes(args.out, args.work)
        return verify(args.out)
    if args.command == "generate-overlaps":
        generate_overlaps(args.out, args.work)
        return verify(args.out)
    generate(args.out, args.work)
    return verify(args.out)


