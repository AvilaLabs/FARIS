# CAD-level models (CadQuery). Lengths in millimetres.

# A sliver is thinner than one faceting chord (1 mm in `chord_cm`); a thin layer that is not a
# sliver is several chords thick, but faceted coarsely enough that the facets misstate its thickness.
SLIVER_MM = 0.5
THIN_LAYER_MM = 6.0


def _box(x, y=None, z=None):
    import cadquery as cq
    return cq.Workplane("XY").box(x, y or x, z or x)


def _cyl(radius, height):
    import cadquery as cq
    return cq.Workplane("XY").circle(radius).extrude(height).translate((0, 0, -height / 2))


def _torus(R, r):
    import cadquery as cq
    return cq.Workplane("XY").add(cq.Solid.makeTorus(R, r))


def build_parts(base: str, s: float, defect: str | None = None, fraction: float | None = None) -> list[tuple[str, object]]:
    """The solids of a base model at scale `s`, as (id, shape). `defect` builds the CAD-level classes.

    `fraction` sizes an overlap: the enlarged solid (core, or port plug) is grown until the volume
    it shares with its neighbour is that fraction of its own, the smaller of the pair."""
    if base == "boxes":
        a = 100.0 * s
        core_edge = a
        if defect == "gap":
            core_edge = 0.9 * a
        if defect == "overlap":
            core_edge = 1.2 * a if fraction is None else a / (1.0 - fraction) ** (1.0 / 3.0)
        shell1_outer = 2 * a
        if defect == "sliver":
            shell1_outer = a + SLIVER_MM
        core = _box(core_edge)
        shell1 = _box(shell1_outer).cut(_box(a))
        shell2 = _box(3 * a).cut(_box(shell1_outer))
        if defect == "zero-volume":
            core = _box(a, a, 1.0e-6)
        parts = [("core", core), ("shell1", shell1), ("shell2", shell2)]
    elif base == "tori":
        R, r1, r2, r3 = 600.0 * s, 100.0 * s, 200.0 * s, 300.0 * s
        r_core = r1
        if defect == "gap":
            r_core = 0.9 * r1
        if defect == "overlap":
            r_core = 1.2 * r1
        r2_eff = r2
        if defect == "sliver":
            r2_eff = r1 + SLIVER_MM
        if defect == "misrepresented-sliver":
            r2_eff = r1 + THIN_LAYER_MM
        parts = [
            ("core", _torus(R, r_core)),
            ("shell1", _torus(R, r2_eff).cut(_torus(R, r1))),
            ("shell2", _torus(R, r3).cut(_torus(R, r2_eff))),
        ]
        if defect == "zero-volume":
            parts[0] = ("core", _torus(R, 1.0e-6))
    elif base == "port":
        w, t, radius = 400.0 * s, 100.0 * s, 60.0 * s
        plug_radius = radius
        if defect == "gap":
            plug_radius = 0.9 * radius
        if defect == "overlap":
            plug_radius = 1.1 * radius if fraction is None else radius / math.sqrt(1.0 - fraction)
        thickness = SLIVER_MM if defect == "sliver" else t
        shell = _box(w, w, thickness).cut(_cyl(radius, thickness * 2))
        plug = _cyl(plug_radius, thickness)
        frame = _box(w + 200.0 * s, w + 200.0 * s, thickness).cut(_box(w, w, thickness * 2))
        if defect == "zero-volume":
            plug = _cyl(radius, 1.0e-6)
        parts = [("plug", plug), ("shell", shell), ("frame", frame)]
    else:
        raise ValueError(base)
    return parts


def chord_cm(base: str, s: float, defect: str | None) -> float:
    """A faceting tolerance a tenth of the thinnest layer (so no clean layer is a sliver)."""
    if defect == "sliver":
        return 0.1
    if defect == "misrepresented-sliver":
        return 0.2  # a third of the 6 mm layer: not a sliver, but the facets of a 0.5 rad torus deviate by it
    if base == "boxes":
        return min(0.1 * s, 0.1)
    if base == "port":
        # the plug's mean thickness 2V/A is 37.5 mm at scale 1: ten tolerances must stay below it
        return round(0.3 * s, 6)
    # the tori layers are 100 mm thick at scale 1: 0.08 of that, in cm
    return round(0.8 * s, 6)


def angular_rad(base: str) -> float:
    """Tori are faceted coarsely so the fixtures stay small; the other bases are flat or nearly so."""
    return 0.5 if base == "tori" else 0.1


def write_step(parts, path: Path) -> None:
    import cadquery as cq
    assembly = cq.Assembly(name=path.stem)
    for name, wp in parts:
        assembly.add(wp.val(), name=name)
    assembly.export(str(path), "STEP")


def run_conversion(step: Path, parts, out_dir: Path, chord: float, imprint: bool = True, angular: float = 0.1) -> dict:
    """The import's own commands: convert (imprinted) or tessellate (not imprinted)."""
    import faris_cad
    tags = [{"step_index": i, "tag": name} for i, (name, _s) in enumerate(parts)]
    tag_file = out_dir / "tags.json"
    tag_file.write_text(json.dumps(tags))
    args = argparse.Namespace(
        step=step, shape_unit_m=1.0e-3, tags=tag_file, out_dir=out_dir, chord_cm=chord, angular=angular,
        imprint_threads=1, shape_cache=None, workers=1, implicit_complement="void", report=out_dir / ("conversion.json" if imprint else "tessellation.json"),
    )
    result = {"command": "convert" if imprint else "tessellate", "chord_cm": chord, "angular_rad": angular}
    try:
        code = faris_cad.convert(args) if imprint else faris_cad.tessellate(args)
        result["exit_code"] = code
        report = json.loads(args.report.read_text()) if args.report.exists() else {}
        result["problems"] = report.get("problems", [])
        result["timing_seconds"] = report.get("timing_seconds", {})
    except BaseException as error:  # the conversion's own failure is a result
        result["exit_code"] = None
        result["error"] = f"{type(error).__name__}: {error}"
        result["trace_tail"] = traceback.format_exc().splitlines()[-3:]
    return result


def run_deviation(step: Path, facets: Path, parts, out_dir: Path) -> dict:
    """GEO-032 on an imprinted model: each solid's largest deviation and whether every point was measured."""
    import faris_cad
    mapping = out_dir / "deviation-map.json"
    mapping.write_text(json.dumps([{"step_index": i, "volume": i + 1} for i in range(len(parts))]))
    report = out_dir / "deviation.json"
    args = argparse.Namespace(
        step=step, shape_unit_m=1.0e-3, shape_cache=None, facets=facets, map=mapping, workers=1,
        block_points=512, occt_points=2000, report=report,
    )
    try:
        faris_cad.deviation(args)
        rows = json.loads(report.read_text())["solids"]
        return {"solids": [
            {"solid_id": parts[r["step_index"]][0], "max_distance_m": r["max_distance_m"], "complete": r["points"] >= r["points_available"]}
            for r in rows
        ]}
    except BaseException as error:
        return {"error": f"{type(error).__name__}: {error}"}


def cad_volumes(step: Path, parts) -> dict:
    """Each solid's CAD volume in m3 as the kernel measures it, by solid id (GEO-012, GEO-030)."""
    import faris_cad
    solids = faris_cad.inspect_step(step, "mm")["solids"]
    return {name: row["cad_volume_m3"] for (name, _shape), row in zip(parts, solids)}


def run_booleans(step: Path, n: int, out_dir: Path) -> dict:
    import faris_cad
    pairs = [[i, j] for i in range(n) for j in range(i + 1, n)]
    pair_file = out_dir / "pairs.json"
    pair_file.write_text(json.dumps(pairs))
    report = out_dir / "booleans.json"
    args = argparse.Namespace(step=step, shape_unit_m=1.0e-3, shape_cache=None, pairs=pair_file, workers=2, pair_timeout=120.0, report=report)
    try:
        faris_cad.overlap_booleans(args)
        found = json.loads(report.read_text())["pairs"]
        return {"pairs": [{k: p.get(k) for k in ("a", "b", "status", "common_volume_m3", "reason")} for p in found]}
    except BaseException as error:
        return {"error": f"{type(error).__name__}: {error}"}


