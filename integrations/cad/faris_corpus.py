#!/usr/bin/env python3
"""Seeded-defect corpus for the CAD integrity checks (GEO-023).

Every model is generated by this script; none is edited by hand. Run it with the
CAD environment (cadquery, cad_to_dagmc, h5py) to regenerate the corpus:

    faris_corpus.py generate --out crates/faris-engine/tests/fixtures/corpus --work /path/scratch
    faris_corpus.py verify   --out crates/faris-engine/tests/fixtures/corpus

`generate-overlaps` adds the small-overlap models (1e-4 and 1e-5 of the smaller solid) and
`record-cad-volumes` adds each clean model's CAD volumes to an existing corpus.json, so neither
regenerates (and re-hashes) the rest.

`verify` needs only the standard library: it checks the sha256 of every committed
file against corpus.json and that the files parse, so a hand edit is caught.

Three base models, each with analytic dimensions (millimetres, STEP declares mm):

    boxes   a core cube inside two nested cubic shells (a few dozen triangles, exact)
    tori    a solid torus inside two nested torus shells (volume 2 pi^2 R r^2)
    port    a slab shell with a cylindrical port through it, and the port plug filling it

Clean models are the imprinted conversions of the bases at eight scales each. Seeded
models come in two families, eleven classes in all:

    mesh-level  open edge, non-manifold edge, inverted normals, self-intersection.
                A clean imprinted model's facets are mutated with a seeded generator.
    CAD-level   overlap, gap, sliver, zero-volume cell, duplicate surface, wrong
                units, missing material. The defect is built in CadQuery, written to
                STEP, and run through the same conversion the import uses.

The fixtures are `faris-facets/v1` files (see faris_facets.py); the two classes
that are about the design file rather than the geometry (wrong units, missing
material) are a STEP file, a design file and the CAD helper's inspection report.
corpus.json lists every model with its class, base, seed, the check that must
find it, the sha256 of every file, and what the CAD-level conversions did.
"""
