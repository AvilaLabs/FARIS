# Mesh-level mutations. A model is a dict: vertices, triangles, surfaces, n_volumes.

def load_model(base: Path) -> dict:
    data = faris_facets.unpack_facets(Path(str(base) + ".facets.bin").read_bytes())
    manifest = json.loads(Path(str(base) + ".facets.json").read_text())
    data["manifest"] = manifest
    return data


def save_model(base: Path, model: dict, source_kind: str, source_sha: str, flags: int, complement=None) -> dict:
    """Write the pair and return its manifest."""
    surfaces = [tuple(s) for s in model["surfaces"]]
    old = model.get("manifest", {})
    per_volume = faris_facets.volumes_from_surfaces(surfaces, model["n_volumes"])
    tags = {v["index"]: v.get("material_tag") for v in old.get("volumes", [])}
    volumes = [
        {"index": i + 1, "global_id": i + 1, "material_tag": tags.get(i + 1), "triangles": per_volume[i]}
        for i in range(model["n_volumes"])
    ]
    binary = faris_facets.pack_facets(model["vertices"], model["triangles"], surfaces, model["n_volumes"], flags)
    manifest = faris_facets.make_manifest(
        binary, volumes, list(range(1, len(surfaces) + 1)), source_kind, source_sha,
        len(model["vertices"]), len(model["triangles"]), len(surfaces), flags, complement,
    )
    faris_facets.write_pair(base, binary, manifest)
    return manifest


def _surface_of_triangle(model: dict, t: int) -> int:
    for i, (first, count, _f, _r) in enumerate(model["surfaces"]):
        if first <= t < first + count:
            return i
    raise IndexError(t)


def _remove_triangle(model: dict, t: int) -> None:
    s = _surface_of_triangle(model, t)
    del model["triangles"][t]
    surfaces = []
    for i, (first, count, f, r) in enumerate(model["surfaces"]):
        if i == s:
            count -= 1
        elif i > s:
            first -= 1
        surfaces.append([first, count, f, r])
    model["surfaces"] = surfaces


def mutate_open_edge(model: dict, rng: random.Random, base: str = "") -> dict:
    """Delete one triangle: three edges are now used once."""
    out = copy.deepcopy(model)
    candidates = [i for i, (_f, c, _a, _b) in enumerate(out["surfaces"]) if c > 1]
    s = rng.choice(candidates)
    first, count, _f, _r = out["surfaces"][s]
    _remove_triangle(out, first + rng.randrange(count))
    return out


def mutate_non_manifold(model: dict, rng: random.Random, base: str = "") -> dict:
    """Copy one triangle into a new surface of the same volume: its edges are used three times."""
    out = copy.deepcopy(model)
    s = rng.randrange(len(out["surfaces"]))
    first, count, fwd, rev = out["surfaces"][s]
    t = list(out["triangles"][first + rng.randrange(count)])
    out["surfaces"].append([len(out["triangles"]), 1, fwd, 0 if fwd else rev])
    out["triangles"].append(t)
    return out


def mutate_inverted(model: dict, rng: random.Random, base: str = "") -> dict:
    """Flip every triangle of the outermost surface (the one facing the implicit complement).

    The port base is plates whose faces all meet along edges, so flipping one face would break
    the orientation of its neighbours (a GEO-020 finding, not the inversion this class seeds);
    there the whole model is inverted, as a STEP file written with reversed shells would be."""
    out = copy.deepcopy(model)
    if base == "port":
        out["triangles"] = [[a, c, b] for a, b, c in out["triangles"]]
        return out
    outer = [i for i, (_f, _c, f, r) in enumerate(out["surfaces"]) if r == 0 and f != 0]
    s = rng.choice(outer)
    first, count, _f, _r = out["surfaces"][s]
    for t in range(first, first + count):
        a, b, c = out["triangles"][t]
        out["triangles"][t] = [a, c, b]
    return out


def mutate_zero_volume(model: dict, rng: random.Random, base: str = "") -> dict:
    """Flatten volume 1 (the innermost solid) into a plane. Its vertices are copied first, so the
    neighbours keep their shape and the solid alone collapses to a sheet of zero volume."""
    out = copy.deepcopy(model)
    first_surface = [i for i, (_f, _c, f, r) in enumerate(out["surfaces"]) if 1 in (f, r)]
    moved: dict[int, int] = {}
    for i in first_surface:
        first, count, _f, _r = out["surfaces"][i]
        for t in range(first, first + count):
            tri = out["triangles"][t]
            for k, v in enumerate(tri):
                if v not in moved:
                    moved[v] = len(out["vertices"])
                    out["vertices"].append(list(out["vertices"][v]))
                tri[k] = moved[v]
    plane = out["vertices"][next(iter(moved.values()))][2]
    for v in moved.values():
        out["vertices"][v][2] = plane
    return out


def mutate_self_intersection(model: dict, rng: random.Random, base: str = "") -> dict:
    """Push one vertex of the outermost surface through the solid to the far side of its centre."""
    out = copy.deepcopy(model)
    outer = [i for i, (_f, _c, f, r) in enumerate(out["surfaces"]) if r == 0 and f != 0]
    s = rng.choice(outer)
    first, count, _f, _r = out["surfaces"][s]
    used = sorted({v for t in out["triangles"][first : first + count] for v in t})
    v = rng.choice(used)
    xs = [out["vertices"][i] for i in used]
    centre = [sum(p[k] for p in xs) / len(xs) for k in range(3)]
    p = out["vertices"][v]
    out["vertices"][v] = [centre[k] - 0.6 * (p[k] - centre[k]) for k in range(3)]
    return out


MUTATORS = {
    "open-edge": mutate_open_edge,
    "non-manifold-edge": mutate_non_manifold,
    "inverted-normals": mutate_inverted,
    "self-intersection": mutate_self_intersection,
    "zero-volume": mutate_zero_volume,
}


